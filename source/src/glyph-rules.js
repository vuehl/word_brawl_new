// Each tuple is [stroke, centerX, centerY, width, height] in the source glyph.
// A composite remains the actual removed strokes, never an invented character.
function multi(to, name, pieces, reason) {
  const left=Math.min(...pieces.map(p=>p[1]-p[3]/2)), top=Math.min(...pieces.map(p=>p[2]-p[4]/2));
  const right=Math.max(...pieces.map(p=>p[1]+p[3]/2)), bottom=Math.max(...pieces.map(p=>p[2]+p[4]/2));
  const w=right-left,h=bottom-top;
  GLYPH_COMPONENTS[name]={pieces:pieces.map(([glyph,x,y,pw,ph])=>({glyph,x:(x-left)/w,y:(y-top)/h,w:pw/w,h:ph/h}))};
  return rule(to,name,(left+right)/2,(top+bottom)/2,w,h,reason);
}
