export function damageChain(glyph) {
  const chain = [], seen = new Set([glyph]);
  while (GLYPH_RULES[glyph]) {
    const next = GLYPH_RULES[glyph];
    if (seen.has(next.to)) throw Error('Cyclic glyph rule: ' + glyph);
    chain.push({from:glyph,...next}); seen.add(next.to); glyph=next.to;
  }
  return chain;
}
export function nextDamageStep(glyph, hpRatio, currentStep, critical=false) {
  const chain=damageChain(glyph);
  if(currentStep>=chain.length)return null;
  const threshold=[.82,.42,.18,.08][Math.min(currentStep,3)];
  return hpRatio<threshold || (critical && currentStep===0) ? chain[currentStep] : null;
}
